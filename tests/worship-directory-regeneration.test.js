#!/usr/bin/env node
'use strict';

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const repo = path.dirname(__dirname);
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'worship-directory-regression-'));

try {
  fs.mkdirSync(path.join(temp, 'scripts'), { recursive: true });
  fs.mkdirSync(path.join(temp, 'docs', 'data'), { recursive: true });
  fs.mkdirSync(path.join(temp, 'docs', 'worship'), { recursive: true });
  fs.copyFileSync(path.join(repo, 'generate-worship-pages.js'), path.join(temp, 'generate-worship-pages.js'));
  fs.copyFileSync(path.join(repo, 'scripts', 'build-worship-directory.js'), path.join(temp, 'scripts', 'build-worship-directory.js'));

  const songs = JSON.parse(fs.readFileSync(path.join(repo, 'docs', 'data', 'worship-songs.json'), 'utf8'));
  const listen = JSON.parse(fs.readFileSync(path.join(repo, 'docs', 'data', 'worship-listen-directory.json'), 'utf8'));
  const approved = listen.songs.find(song => song.doctrinal_status === 'approved');
  assert(songs.length > 0, 'fixture requires at least one worship song');
  assert(approved, 'fixture requires at least one approved Listen Directory song');

  fs.writeFileSync(path.join(temp, 'docs', 'data', 'worship-songs.json'), JSON.stringify([songs[0]]));
  fs.writeFileSync(path.join(temp, 'docs', 'data', 'worship-overrides.json'), '{}');
  fs.writeFileSync(path.join(temp, 'docs', 'data', 'worship-nonworship.json'), '[]');
  fs.writeFileSync(path.join(temp, 'docs', 'data', 'worship-listen-directory.json'), JSON.stringify({ songs: [approved] }));
  fs.writeFileSync(path.join(temp, 'docs', 'worship', 'directory.html'), 'sentinel that must be rebuilt');
  fs.writeFileSync(path.join(temp, 'docs', 'worship', 'stale-song.html'), 'stale');

  execFileSync(process.execPath, [path.join(temp, 'generate-worship-pages.js'), '--pages'], {
    cwd: temp,
    stdio: 'pipe',
  });

  const directory = path.join(temp, 'docs', 'worship', 'directory.html');
  const html = fs.readFileSync(directory, 'utf8');
  assert.match(html, /<h1>Listen Directory<\/h1>/, 'regeneration must rebuild the Listen Directory');
  assert.match(html, /GENERATED by scripts\/build-worship-directory\.js/, 'page must retain its generated-artifact marker');
  assert(html.includes(approved.title), 'rebuilt directory must contain approved catalog content');
  assert(fs.existsSync(path.join(temp, 'docs', 'worship', songs[0].slug + '.html')), 'song page should still be generated');
  assert(!fs.existsSync(path.join(temp, 'docs', 'worship', 'stale-song.html')), 'stale song pages should still be pruned');

  execFileSync(process.execPath, [path.join(temp, 'scripts', 'build-worship-directory.js'), '--check'], {
    cwd: temp,
    stdio: 'pipe',
  });

  console.log('PASS worship regeneration preserves and rebuilds directory.html');
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}
