def add_batch(data, new_refs):
    added = 0
    for key, refs in new_refs.items():
        if key not in data:
            data[key] = refs
            added += 1
        else:
            # Merge without duplicates
            existing = set(data[key])
            for r in refs:
                if r not in existing:
                    data[key].append(r)
                    existing.add(r)
    return added

