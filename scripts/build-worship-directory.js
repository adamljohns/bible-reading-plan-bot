function main() {
  const data = JSON.parse(fs.readFileSync(DATA, 'utf8'));
  const html = render(data);

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current === html) {
      console.log('OK — directory.html matches worship-listen-directory.json');
      process.exit(0);
    }
    console.error('DRIFT — directory.html does not match the catalog. Run without --check to rebuild.');
    process.exit(1);
  }

  fs.writeFileSync(OUT, html);
  const songs = data.songs.filter(s => s.doctrinal_status === 'approved');
  console.log(`wrote ${path.relative(REPO, OUT)}`);
  console.log(`  ${songs.length} approved cards`);
  console.log(`  youtube links: ${songs.filter(s => s.youtube_url).length}`);
  console.log(`  amazon links:  ${songs.filter(s => s.amazon_music_url).length}`);
  console.log(`  chord links:   ${songs.filter(s => s.songbook_path).length}`);
}

main();
