#!/usr/bin/env node
/* build-worship-directory.js — render docs/worship/directory.html from
 * docs/data/worship-listen-directory.json.  CID PJG-0809-MEISTER1.
 *
 * Why this exists: the Phase 1 directory (9fbc42ad3c0) shipped as hand-written
 * HTML with no generator, and the HTML had already drifted from the JSON before
 * anyone loaded the page — 22 of 40 cards pointed at a DIFFERENT YouTube video
 * than the catalog, and all 40 Amazon buttons were href="#" while the JSON
 * carried real URLs. Both are the same defect: two copies of the truth.
 *
 * The repo already knows this lesson — churches.json has generate-church-pages.js
 * and CLAUDE.md says "don't hand-edit HTML in docs/churches/, it's generator
 * output." Same rule now applies here.
 *
 * Usage:
 *   node scripts/build-worship-directory.js          # write the page
 *   node scripts/build-worship-directory.js --check  # verify page matches JSON, exit 1 on drift
 */
'use strict';

const fs = require('fs');
const path = require('path');

const REPO = path.dirname(__dirname);
const DATA = path.join(REPO, 'docs', 'data', 'worship-listen-directory.json');
const OUT = path.join(REPO, 'docs', 'worship', 'directory.html');

const esc = s => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#x27;');

/* Attribute payload for client-side filtering. Lowercased and stripped of the
 * punctuation people don't type — searching "lords my shepherd" should find
 * "The Lord's My Shepherd (Ps 23)". */
const searchKey = song => [
  song.title,
  (song.artists || []).join(' '),
  (song.themes || []).join(' '),
].join(' ').toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim();

function card(song) {
  const artists = (song.artists || []).join(', ');
  const themes = (song.themes || []).join(' · ');
  const actions = [];

  if (song.youtube_url) {
    actions.push(`      <a class="btn gold" href="${esc(song.youtube_url)}" target="_blank" rel="noopener noreferrer">YouTube<span class="sr-only"> — ${esc(song.title)}</span></a>`);
  }
  // The Phase 1 bug: this link existed in the catalog and never reached the page.
  if (song.amazon_music_url) {
    actions.push(`      <a class="btn ghost" href="${esc(song.amazon_music_url)}" target="_blank" rel="noopener noreferrer">Amazon Music<span class="sr-only"> — ${esc(song.title)}</span></a>`);
  }
  if (song.songbook_path) {
    actions.push(`      <a class="btn ghost" href="${esc(song.songbook_path)}">Chords<span class="sr-only"> for ${esc(song.title)}</span></a>`);
  }

  const note = song.notes
    ? `\n    <p class="note-song">${esc(song.notes)}</p>`
    : '';

  return `    <article class="card" data-style="${esc(song.style)}" data-search="${esc(searchKey(song))}">
      <h3>${esc(song.title)}</h3>
      <p class="meta">${esc(artists)}</p>
      <p class="themes">${esc(themes)}</p>${note}
      <div class="actions">
${actions.join('\n')}
      </div>
    </article>`;
}

