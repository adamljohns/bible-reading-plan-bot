def valid_ref(ref):
    parts = ref.split("_")
    if len(parts) != 3: return False
    try:
        b,c,v = int(parts[0]), int(parts[1]), int(parts[2])
        return 1 <= b <= 66 and 1 <= c <= MAX_CHAPTERS.get(b,0) and v >= 1
    except: return False

def load():
    with open(XREF) as f: return json.load(f)

def save(data):
    with open(XREF,"w") as f: json.dump(data, f, separators=(",",":"))

def commit(count, batch):
    os.chdir(REPO)
    subprocess.run(["git","add","-A"], check=True)
    subprocess.run(["git","commit","-m",f"BTE: cross-refs +{count} (batch {batch})"], check=True)
    subprocess.run(["git","push","origin","main"], check=True)
    print(f"✅ Batch {batch}: +{count} committed & pushed")

def merge_batch(data, refs):
    added = 0
    bad = []
    for k, vals in refs.items():
        if not valid_ref(k):
            bad.append(f"BAD KEY: {k}")
            continue
        clean = [v for v in vals if valid_ref(v)]
        for bv in [v for v in vals if not valid_ref(v)]:
            bad.append(f"BAD VAL: {bv} in {k}")
        if k not in data:
            data[k] = clean
            added += 1
        else:
            existing = set(data[k])
            new_added = False
            for v in clean:
                if v not in existing:
                    data[k].append(v)
                    existing.add(v)
                    new_added = True
            if new_added:
                added += 1
    if bad:
        print(f"  ⚠️  {len(bad)} bad refs skipped: {bad[:5]}...")
    return added

